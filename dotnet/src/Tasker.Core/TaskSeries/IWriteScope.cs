namespace Tasker.Core.TaskSeries;

/// <summary>
/// Атомарная секция записи проекта: пока идёт <paramref name="action"/>, другие процессы (и другие запросы) не выдают номера
/// и не меняют задачи проекта, а чтение хранилищ внутри видит все уже записанные изменения — в том числе принесённые
/// <c>git pull</c>, о которых кэш мог ещё не знать. Так «взять максимальный номер + 1» и «записать задачу» не перебьют друг друга.
/// <para>
/// Файлы: межпроцессная блокировка записи (<c>.cache/write.lock</c>) и сверка индекса задач проекта перед действием.
/// БД: транзакция (с повтором, если сработал уникальный индекс номеров).
/// Вложенный вызов из того же потока выполнения не блокирует сам себя.
/// </para>
/// </summary>
public interface IWriteScope
{
    Task<T> Exclusive<T>(Guid projectId, Func<Task<T>> action, CancellationToken ct = default);
}
