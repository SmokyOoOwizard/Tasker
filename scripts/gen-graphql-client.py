class GraphQLError(Exception):
    pass


TOKEN = re.compile(
    r'(?P<ws>[\s,﻿]+)|(?P<comment>#[^\n\r]*)|(?P<block>"""(?:\\"""|[^"]|"(?!""))*""")'
    r'|(?P<string>"(?:\\.|[^"\\\n\r])*")|(?P<spread>\.\.\.)|(?P<punct>[!$&()\:=@\[\]{}|])'
    r"|(?P<number>-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?)|(?P<name>[_A-Za-z][_0-9A-Za-z]*)"
)


def tokenize(text, source):
    tokens = []
    pos = 0
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if not m:
            line = text.count("\n", 0, pos) + 1
            raise GraphQLError("%s:%d: непонятный символ %r" % (source, line, text[pos]))
        kind = m.lastgroup
        line = text.count("\n", 0, pos) + 1
        pos = m.end()
        if kind in ("ws", "comment"):
            continue
        value = m.group(kind)
        if kind == "block":
            kind, value = "string", value[3:-3].replace('\\"""', '"""')
        elif kind == "string":
            value = json.loads(value)
        tokens.append((kind, value, line))
    tokens.append(("eof", None, text.count("\n") + 1))
    return tokens


class Parser:
    def __init__(self, text, source):
        self.tokens = tokenize(text, source)
        self.i = 0
        self.source = source

    def peek(self, offset=0):
        return self.tokens[min(self.i + offset, len(self.tokens) - 1)]

    def fail(self, message):
        raise GraphQLError("%s:%d: %s" % (self.source, self.peek()[2], message))

    def next(self):
        token = self.tokens[self.i]
        self.i += 1
        return token

    def at(self, kind, value=None):
        token = self.peek()
        return token[0] == kind and (value is None or token[1] == value)

    def skip(self, kind, value=None):
        if self.at(kind, value):
            self.next()
            return True
        return False

    def expect(self, kind, value=None):
        if not self.at(kind, value):
            self.fail("ожидалось %s, а встретилось %r" % (value or kind, self.peek()[1]))
        return self.next()[1]

    def name(self):
        return self.expect("name")

    def type_ref(self):
        if self.skip("punct", "["):
            inner = self.type_ref()
            self.expect("punct", "]")
            ref = ("list", inner)
        else:
            ref = ("named", self.name())
        if self.skip("punct", "!"):
            ref = ("nonnull", ref)
        return ref

    def value(self, const=False):
        kind, value, _ = self.peek()
        if kind == "punct" and value == "$":
            if const:
                self.fail("переменная в константе")
            self.next()
            return ("variable", self.name())
        if kind == "number":
            self.next()
            return ("float", float(value)) if any(c in value for c in ".eE") else ("int", int(value))
        if kind == "string":
            self.next()
            return ("string", value)
        if kind == "name":
            self.next()
            if value in ("true", "false"):
                return ("bool", value == "true")
            if value == "null":
                return ("null", None)
            return ("enum", value)
        if self.skip("punct", "["):
            items = []
            while not self.skip("punct", "]"):
                items.append(self.value(const))
            return ("list", items)
        if self.skip("punct", "{"):
            fields = []
            while not self.skip("punct", "}"):
                key = self.name()
                self.expect("punct", ":")
                fields.append((key, self.value(const)))
            return ("object", fields)
        self.fail("ожидалось значение")

    def arguments(self, const=False):
        args = []
        if self.skip("punct", "("):
            while not self.skip("punct", ")"):
                key = self.name()
                self.expect("punct", ":")
                args.append((key, self.value(const)))
        return args

    def directives(self):
        result = []
        while self.skip("punct", "@"):
            result.append((self.name(), self.arguments()))
        return result


def parse_schema(text, source):
    p = Parser(text, source)
    types = {}
    roots = {"query": "Query", "mutation": "Mutation", "subscription": "Subscription"}
    while not p.at("eof"):
        p.skip("string")
        keyword = p.name()
        if keyword == "schema":
            p.directives()
            p.expect("punct", "{")
            while not p.skip("punct", "}"):
                op = p.name()
                p.expect("punct", ":")
                roots[op] = p.name()
        elif keyword in ("type", "interface", "input"):
            name = p.name()
            if keyword != "input" and p.skip("name", "implements"):
                p.skip("punct", "&")
                p.name()
                while p.skip("punct", "&"):
                    p.name()
            p.directives()
            fields = {}
            if p.skip("punct", "{"):
                while not p.skip("punct", "}"):
                    p.skip("string")
                    fname = p.name()
                    args = {}
                    if p.skip("punct", "("):
                        while not p.skip("punct", ")"):
                            p.skip("string")
                            aname = p.name()
                            p.expect("punct", ":")
                            atype = p.type_ref()
                            default = p.value(const=True) if p.skip("punct", "=") else None
                            p.directives()
                            args[aname] = (atype, default)
                    if keyword == "input":
                        p.expect("punct", ":")
                        ftype = p.type_ref()
                        if p.skip("punct", "="):
                            p.value(const=True)
                    else:
                        p.expect("punct", ":")
                        ftype = p.type_ref()
                    p.directives()
                    fields[fname] = (ftype, args)
            types[name] = {"kind": {"type": "object"}.get(keyword, keyword), "fields": fields}
        elif keyword == "enum":
            name = p.name()
            p.directives()
            values = []
            p.expect("punct", "{")
            while not p.skip("punct", "}"):
                p.skip("string")
                values.append(p.name())
                p.directives()
            types[name] = {"kind": "enum", "values": values}
        elif keyword == "scalar":
            name = p.name()
            p.directives()
            types[name] = {"kind": "scalar"}
        elif keyword == "union":
            name = p.name()
            p.directives()
            p.expect("punct", "=")
            p.skip("punct", "|")
            members = [p.name()]
            while p.skip("punct", "|"):
                members.append(p.name())
            types[name] = {"kind": "union", "members": members}
        elif keyword == "directive":
            p.expect("punct", "@")
            p.name()
            p.arguments()
            if p.at("punct", "("):
                p.fail("аргументы директив схемы не поддерживаются")
            p.skip("name", "repeatable")
            p.expect("name", "on")
            p.skip("punct", "|")
            p.name()
            while p.skip("punct", "|"):
                p.name()
        else:
            p.fail("неизвестное определение %s" % keyword)
    for name in ("String", "Int", "Float", "Boolean", "ID"):
        types.setdefault(name, {"kind": "scalar"})
    return types, roots


def parse_selection_set(p):
    p.expect("punct", "{")
    selections = []
    while not p.skip("punct", "}"):
        line = p.peek()[2]
        if p.skip("spread"):
            if p.at("name") and p.peek()[1] != "on":
                name = p.name()
                if p.directives():
                    p.fail("директивы не поддерживаются")
                selections.append({"kind": "spread", "name": name, "line": line})
            else:
                condition = p.name() if p.skip("name", "on") else None
                if condition is None and p.at("name"):
                    p.fail("ожидалось on")
                if p.directives():
                    p.fail("директивы не поддерживаются")
                selections.append({"kind": "inline", "on": condition, "selections": parse_selection_set(p), "line": line})
        else:
            alias = None
            name = p.name()
            if p.skip("punct", ":"):
                alias, name = name, p.name()
            args = p.arguments()
            if p.directives():
                p.fail("директивы не поддерживаются")
            nested = parse_selection_set(p) if p.at("punct", "{") else None
            selections.append({"kind": "field", "name": name, "alias": alias, "args": args, "selections": nested, "line": line})
    return selections


def parse_operations(text, source):
    p = Parser(text, source)
    operations = []
    fragments = []
    while not p.at("eof"):
        line = p.peek()[2]
        keyword = p.name()
        if keyword in ("query", "mutation", "subscription"):
            if not p.at("name"):
                p.fail("у операции должно быть имя")
            name = p.name()
            variables = []
            if p.skip("punct", "("):
                while not p.skip("punct", ")"):
                    p.expect("punct", "$")
                    vname = p.name()
                    p.expect("punct", ":")
                    vtype = p.type_ref()
                    default = p.value(const=True) if p.skip("punct", "=") else None
                    variables.append({"name": vname, "type": vtype, "default": default})
            if p.directives():
                p.fail("директивы не поддерживаются")
            operations.append({"kind": keyword, "name": name, "variables": variables, "selections": parse_selection_set(p), "source": source, "line": line})
        elif keyword == "fragment":
            name = p.name()
            p.expect("name", "on")
            on = p.name()
            if p.directives():
                p.fail("директивы не поддерживаются")
            fragments.append({"name": name, "on": on, "selections": parse_selection_set(p), "source": source, "line": line})
        else:
            p.fail("ожидалась операция или фрагмент, а встретилось %s" % keyword)
    return operations, fragments


def base_name(ref):
    while ref[0] != "named":
        ref = ref[1]
    return ref[1]


def strip_nonnull(ref):
    return ref[1] if ref[0] == "nonnull" else ref


def print_type(ref):
    if ref[0] == "nonnull":
        return print_type(ref[1]) + "!"
    if ref[0] == "list":
        return "[" + print_type(ref[1]) + "]"
    return ref[1]


def print_value(value):
    kind, v = value
    if kind == "variable":
        return "$" + v
    if kind == "int":
        return str(v)
    if kind == "float":
        return repr(v)
    if kind == "string":
        return json.dumps(v, ensure_ascii=False)
    if kind == "bool":
        return "true" if v else "false"
    if kind == "null":
        return "null"
    if kind == "enum":
        return v
    if kind == "list":
        return "[" + ", ".join(print_value(x) for x in v) + "]"
    return "{" + ", ".join("%s: %s" % (k, print_value(x)) for k, x in v) + "}"


class Generator:
    def __init__(self, types, roots, operations, fragments):
        self.types = types
        self.roots = roots
        self.operations = operations
        self.fragments = {}
        for fragment in fragments:
            if fragment["name"] in self.fragments:
                raise GraphQLError("%s:%d: фрагмент %s объявлен дважды" % (fragment["source"], fragment["line"], fragment["name"]))
            self.fragments[fragment["name"]] = fragment
        names = set()
        for op in operations:
            swift = self.operation_type_name(op)
            if swift in names or swift in self.fragments:
                raise GraphQLError("%s:%d: имя %s уже занято" % (op["source"], op["line"], swift))
            names.add(swift)

    def fail(self, where, message):
        raise GraphQLError("%s:%d: %s" % (where["source"], where["line"], message))

    def operation_type_name(self, op):
        suffix = op["kind"].capitalize()
        return op["name"] if op["name"].endswith(suffix) else op["name"] + suffix

    def object_type(self, name):
        t = self.types.get(name)
        if not t or t["kind"] not in ("object", "interface"):
            return None
        return t

    def check_value_type(self, where, value, ref, variables, used):
        kind, v = value
        if kind == "variable":
            if v not in variables:
                self.fail(where, "переменная $%s не объявлена" % v)
            used.add(v)
            declared = variables[v]["type"]
            if declared[0] != "nonnull" and variables[v]["default"] is None and ref[0] == "nonnull":
                self.fail(where, "переменная $%s может быть null, а аргумент обязателен" % v)
            if print_type(strip_nonnull(declared)).replace("!", "") != print_type(strip_nonnull(ref)).replace("!", ""):
                self.fail(where, "тип переменной $%s (%s) не подходит к %s" % (v, print_type(declared), print_type(ref)))
            return
        if kind == "null":
            if ref[0] == "nonnull":
                self.fail(where, "null в обязательном аргументе")
            return
        ref = strip_nonnull(ref)
        if ref[0] == "list":
            for item in (v if kind == "list" else [value]):
                self.check_value_type(where, item, ref[1], variables, used)
            return
        target = self.types[ref[1]]
        if target["kind"] == "enum":
            if kind != "enum" or v not in target["values"]:
                self.fail(where, "значение %s не входит в %s" % (print_value(value), ref[1]))
            return
        expected = {"Int": ("int",), "Float": ("int", "float"), "Boolean": ("bool",), "String": ("string",), "ID": ("string", "int"), "UUID": ("string",), "DateTime": ("string",)}
        if ref[1] in expected and kind not in expected[ref[1]]:
            self.fail(where, "значение %s не подходит к %s" % (print_value(value), ref[1]))

    def collect(self, where, type_name, selections, variables, used, fragments_used, stack):
        result = {}
        order = []
        t = self.object_type(type_name)
        for sel in selections:
            loc = {"source": where["source"], "line": sel["line"]}
            if sel["kind"] == "spread":
                fragment = self.fragments.get(sel["name"])
                if not fragment:
                    self.fail(loc, "фрагмент %s не найден" % sel["name"])
                if fragment["on"] != type_name:
                    self.fail(loc, "фрагмент %s объявлен на %s, а применён к %s" % (sel["name"], fragment["on"], type_name))
                if sel["name"] in stack:
                    self.fail(loc, "фрагмент %s ссылается сам на себя" % sel["name"])
                fragments_used.add(sel["name"])
                nested = self.collect(fragment, type_name, fragment["selections"], variables, used, fragments_used, stack + [sel["name"]])
                self.merge(loc, result, order, nested)
                continue
            if sel["kind"] == "inline":
                if sel["on"] not in (None, type_name):
                    self.fail(loc, "уточнение типа ... on %s внутри %s не поддерживается" % (sel["on"], type_name))
                nested = self.collect(where, type_name, sel["selections"], variables, used, fragments_used, stack)
                self.merge(loc, result, order, nested)
                continue
            name = sel["name"]
            key = sel["alias"] or name
            if name == "__typename":
                if sel["args"] or sel["selections"]:
                    self.fail(loc, "у __typename нет аргументов и выборки")
                field = {"name": name, "alias": sel["alias"], "args": [], "type": ("nonnull", ("named", "String")), "children": None, "spread": None, "user": True}
                self.merge(loc, result, order, ({key: field}, [key]))
                continue
            if name not in t["fields"]:
                self.fail(loc, "у типа %s нет поля %s" % (type_name, name))
            ftype, fargs = t["fields"][name]
            given = {}
            for aname, avalue in sel["args"]:
                if aname not in fargs:
                    self.fail(loc, "у поля %s.%s нет аргумента %s" % (type_name, name, aname))
                if aname in given:
                    self.fail(loc, "аргумент %s указан дважды" % aname)
                self.check_value_type(loc, avalue, fargs[aname][0], variables, used)
                given[aname] = avalue
            for aname, (atype, default) in fargs.items():
                if atype[0] == "nonnull" and default is None and aname not in given:
                    self.fail(loc, "не указан обязательный аргумент %s поля %s.%s" % (aname, type_name, name))
            target = base_name(ftype)
            children = None
            spread = None
            if self.object_type(target):
                if not sel["selections"]:
                    self.fail(loc, "у поля %s.%s типа %s нужна выборка { … }" % (type_name, name, target))
                children = self.collect(where, target, sel["selections"], variables, used, fragments_used, stack)
                only = sel["selections"]
                if len(only) == 1 and only[0]["kind"] == "spread":
                    spread = only[0]["name"]
            else:
                if self.types.get(target, {}).get("kind") == "union":
                    self.fail(loc, "объединения типов не поддерживаются")
                if sel["selections"]:
                    self.fail(loc, "у скалярного поля %s.%s не может быть выборки" % (type_name, name))
            field = {"name": name, "alias": sel["alias"], "args": sel["args"], "type": ftype, "children": children, "spread": spread, "user": True}
            self.merge(loc, result, order, ({key: field}, [key]))
        return result, order

    def merge(self, loc, result, order, incoming):
        fields, keys = incoming
        for key in keys:
            field = fields[key]
            if key not in result:
                result[key] = field
                order.append(key)
                continue
            current = result[key]
            if current["name"] != field["name"] or [(k, print_value(v)) for k, v in current["args"]] != [(k, print_value(v)) for k, v in field["args"]]:
                self.fail(loc, "поле %s выбрано дважды по-разному" % key)
            if current["children"] is not None:
                merged = ({k: v for k, v in current["children"][0].items()}, list(current["children"][1]))
                self.merge(loc, merged[0], merged[1], field["children"])
                spread = current["spread"] if current["spread"] == field["spread"] else None
                result[key] = dict(current, children=merged, spread=spread)

    def with_cache_keys(self, type_name, children):
        fields, order = children
        fields = dict(fields)
        order = list(order)
        extra = []
        if "__typename" not in fields:
            fields["__typename"] = {"name": "__typename", "alias": None, "args": [], "type": ("nonnull", ("named", "String")), "children": None, "spread": None, "user": False}
            extra.append("__typename")
        t = self.object_type(type_name)
        if "id" in t["fields"] and "id" not in fields:
            fields["id"] = {"name": "id", "alias": None, "args": [], "type": t["fields"]["id"][0], "children": None, "spread": None, "user": False}
            extra.append("id")
        return fields, extra + order

    def print_selections(self, type_name, selections, indent):
        t = self.object_type(type_name)
        names = [s.get("alias") or s.get("name") for s in selections if s["kind"] == "field"]
        lines = []
        pad = "  " * indent
        if "__typename" not in names:
            lines.append(pad + "__typename")
        if "id" in t["fields"] and "id" not in names:
            lines.append(pad + "id")
        for sel in selections:
            if sel["kind"] == "spread":
                lines.append(pad + "..." + sel["name"])
            elif sel["kind"] == "inline":
                head = "... on %s" % sel["on"] if sel["on"] else "..."
                lines.append(pad + head + " {")
                lines.extend(self.print_selections(type_name, sel["selections"], indent + 1))
                lines.append(pad + "}")
            else:
                text = (sel["alias"] + ": " if sel["alias"] else "") + sel["name"]
                if sel["args"]:
                    text += "(" + ", ".join("%s: %s" % (k, print_value(v)) for k, v in sel["args"]) + ")"
                if sel["selections"]:
                    target = base_name(self.object_type(type_name)["fields"][sel["name"]][0])
                    lines.append(pad + text + " {")
                    lines.extend(self.print_selections(target, sel["selections"], indent + 1))
                    lines.append(pad + "}")
                else:
                    lines.append(pad + text)
        return lines

    def document(self, op, fragments_used):
        root = self.roots[op["kind"]]
        head = "%s %s" % (op["kind"], op["name"])
        if op["variables"]:
            parts = []
            for v in op["variables"]:
                text = "$%s: %s" % (v["name"], print_type(v["type"]))
                if v["default"] is not None:
                    text += " = " + print_value(v["default"])
                parts.append(text)
            head += "(" + ", ".join(parts) + ")"
        lines = [head + " {"]
        lines.extend(self.print_root(root, op["selections"], 1))
        lines.append("}")
        for name in sorted(fragments_used):
            fragment = self.fragments[name]
            lines.append("fragment %s on %s {" % (name, fragment["on"]))
            lines.extend(self.print_selections(fragment["on"], fragment["selections"], 1))
            lines.append("}")
        return "\n".join(lines)

    def print_root(self, root, selections, indent):
        lines = []
        pad = "  " * indent
        for sel in selections:
            if sel["kind"] != "field":
                lines.append(pad + "...")
                continue
            text = (sel["alias"] + ": " if sel["alias"] else "") + sel["name"]
            if sel["args"]:
                text += "(" + ", ".join("%s: %s" % (k, print_value(v)) for k, v in sel["args"]) + ")"
            if sel["selections"]:
                target = base_name(self.object_type(root)["fields"][sel["name"]][0])
                lines.append(pad + text + " {")
                lines.extend(self.print_selections(target, sel["selections"], indent + 1))
                lines.append(pad + "}")
            else:
                lines.append(pad + text)
        return lines

    def check_root_selections(self, op):
        for sel in op["selections"]:
            if sel["kind"] != "field":
                self.fail({"source": op["source"], "line": sel["line"]}, "фрагменты на корневом уровне не поддерживаются")

    def analyze(self, op):
        root = self.roots.get(op["kind"])
        if op["kind"] == "mutation" or not root or root not in self.types:
            self.fail(op, "операции %s не поддерживаются: изменения идут через REST" % op["kind"])
        self.check_root_selections(op)
        variables = {}
        for v in op["variables"]:
            if v["name"] in variables:
                self.fail(op, "переменная $%s объявлена дважды" % v["name"])
            target = base_name(v["type"])
            if target not in self.types or self.types[target]["kind"] not in ("scalar", "enum", "input"):
                self.fail(op, "тип переменной $%s (%s) не найден или не входной" % (v["name"], target))
            if self.types[target]["kind"] == "input":
                self.fail(op, "входные объекты не поддерживаются")
            variables[v["name"]] = v
        used = set()
        fragments_used = set()
        tree = self.collect(op, root, op["selections"], variables, used, fragments_used, [])
        unused = [v for v in variables if v not in used]
        if unused:
            self.fail(op, "переменная $%s не используется" % unused[0])
        if op["kind"] == "subscription" and len(tree[1]) != 1:
            self.fail(op, "в подписке должно быть ровно одно поле")
        return tree, variables, fragments_used

    def swift_scalar(self, name):
        t = self.types.get(name)
        if t is None:
            raise GraphQLError("тип %s не найден в схеме" % name)
        if t["kind"] == "enum":
            return name
        if name not in SCALARS:
            raise GraphQLError("скаляр %s не поддерживается генератором" % name)
        return SCALARS[name]

    def swift_type(self, ref, leaf):
        if ref[0] == "nonnull":
            inner = ref[1]
            if inner[0] == "list":
                return "[" + self.swift_type(inner[1], leaf) + "]"
            return leaf
        if ref[0] == "list":
            return "[" + self.swift_type(ref[1], leaf) + "]?"
        return leaf + "?"

    def emit_struct(self, out, name, type_name, children, indent):
        fields, order = children
        pad = "    " * indent
        out.append("%spublic struct %s: Hashable, Sendable, Decodable {" % (pad, name))
        props = []
        nested = []
        used_names = set()
        for key in order:
            field = fields[key]
            if not field["user"]:
                continue
            target = base_name(field["type"])
            if field["children"] is not None:
                if field["spread"] is not None:
                    leaf = field["spread"]
                else:
                    leaf = type_name_for(key, used_names)
                    nested.append((leaf, target, field["children"]))
            elif key == "__typename":
                leaf = "String"
            else:
                leaf = self.swift_scalar(target)
            props.append((key, self.swift_type(field["type"], leaf)))
        for key, swift in props:
            out.append("%s    public var %s: %s" % (pad, ident(key), swift))
        if props:
            out.append("")
            params = ", ".join("%s: %s" % (ident(key), swift) for key, swift in props)
            out.append("%s    public init(%s) {" % (pad, params))
            for key, _ in props:
                out.append("%s        self.%s = %s" % (pad, key, ident(key)))
            out.append("%s    }" % pad)
        else:
            out.append("%s    public init() {}" % pad)
        for leaf, target, sub in nested:
            out.append("")
            self.emit_struct(out, leaf, target, sub, indent + 1)
        out.append("%s}" % pad)

    def emit_selections(self, out, type_name, children, indent, root=False):
        fields, order = children if root else self.with_cache_keys(type_name, children)
        pad = "    " * indent
        for i, key in enumerate(order):
            field = fields[key]
            comma = "," if i < len(order) - 1 else ""
            parts = [swift_string(field["name"])]
            if field["alias"]:
                parts.append("alias: " + swift_string(field["alias"]))
            if field["args"]:
                parts.append("arguments: [" + ", ".join("%s: %s" % (swift_string(k), swift_argument(v)) for k, v in field["args"]) + "]")
            if field["children"] is None:
                out.append("%sGraphQLField(%s)%s" % (pad, ", ".join(parts), comma))
            else:
                out.append("%sGraphQLField(%s, selections: [" % (pad, ", ".join(parts)))
                self.emit_selections(out, base_name(field["type"]), field["children"], indent + 1)
                out.append("%s])%s" % (pad, comma))

    def emit_operation(self, out, op):
        tree, variables, fragments_used = self.analyze(op)
        closure = set(fragments_used)
        name = self.operation_type_name(op)
        protocol = {"query": "GraphQLQuery", "subscription": "GraphQLSubscription"}[op["kind"]]
        out.append("public struct %s: %s {" % (name, protocol))
        out.append("    public static let operationName = %s" % swift_string(op["name"]))
        out.append("    public static let document = %s" % swift_multiline(self.document(op, closure), 1))
        out.append("    public static let selections: [GraphQLField] = [")
        self.emit_selections(out, self.roots[op["kind"]], tree, 2, root=True)
        out.append("    ]")
        out.append("")
        params = []
        for v in op["variables"]:
            target = base_name(v["type"])
            swift = self.swift_type(v["type"], self.swift_scalar(target))
            optional = swift.endswith("?")
            out.append("    public var %s: %s" % (ident(v["name"]), swift))
            params.append((v["name"], swift, optional))
        if params:
            out.append("")
            out.append("    public init(%s) {" % ", ".join("%s: %s%s" % (ident(n), s, " = nil" if o else "") for n, s, o in params))
            for n, _, _ in params:
                out.append("        self.%s = %s" % (n, ident(n)))
            out.append("    }")
            out.append("")
            out.append("    public var variables: [String: JSONValue] {")
            out.append("        var result: [String: JSONValue] = [:]")
            for n, _, o in params:
                if o:
                    out.append("        if let %s { result[%s] = %s.graphQLValue }" % (ident(n), swift_string(n), ident(n)))
                else:
                    out.append("        result[%s] = %s.graphQLValue" % (swift_string(n), ident(n)))
            out.append("        return result")
            out.append("    }")
        else:
            out.append("    public init() {}")
            out.append("")
            out.append("    public var variables: [String: JSONValue] { [:] }")
        out.append("")
        self.emit_struct(out, "Data", self.roots[op["kind"]], tree, 1)
        out.append("}")

    def emit_fragment(self, out, fragment):
        if not self.object_type(fragment["on"]):
            self.fail(fragment, "тип %s не найден" % fragment["on"])
        tree = self.collect(fragment, fragment["on"], fragment["selections"], {}, set(), set(), [fragment["name"]])
        self.emit_struct(out, fragment["name"], fragment["on"], tree, 0)

    def schema_file(self):
        out = [HEADER, "import Foundation", ""]
        enums = sorted(name for name, t in self.types.items() if t["kind"] == "enum" and not name.startswith("__"))
        for name in enums:
            out.append("public enum %s: String, GraphQLEnum, CaseIterable {" % name)
            for value in self.types[name]["values"]:
                case = value if re.fullmatch(r"[_A-Za-z][_0-9A-Za-z]*", value) else None
                if case is None:
                    raise GraphQLError("значение %s.%s не годится как имя case" % (name, value))
                if case == value:
                    out.append("    case %s" % ident(case))
                else:
                    out.append("    case %s = %s" % (ident(case), swift_string(value)))
            out.append("}")
            out.append("")
        return "\n".join(out).rstrip() + "\n"

    def operations_file(self, ops, fragments):
        out = [HEADER, "import Foundation", ""]
        for fragment in fragments:
            self.emit_fragment(out, fragment)
            out.append("")
        for op in ops:
            self.emit_operation(out, op)
            out.append("")
        return "\n".join(out).rstrip() + "\n"


def type_name_for(key, used):
    name = key[0].upper() + key[1:]
    if name in RESERVED_TYPE_NAMES:
        name += "Item"
    base = name
    n = 2
    while name in used:
        name = "%s%d" % (base, n)
        n += 1
    used.add(name)
    return name


def ident(name):
    return "`%s`" % name if name in SWIFT_KEYWORDS else name


def swift_string(text):
    return json.dumps(text, ensure_ascii=False)


def swift_multiline(text, indent):
    pad = "    " * indent
    body = "\n".join(pad + line if line else line for line in text.replace("\\", "\\\\").split("\n"))
    return '"""\n%s\n%s"""' % (body, pad)


def swift_json(value):
    kind, v = value
    if kind == "int":
        return ".int(%d)" % v
    if kind == "float":
        return ".double(%r)" % v
    if kind == "string":
        return ".string(%s)" % swift_string(v)
    if kind == "bool":
        return ".bool(%s)" % ("true" if v else "false")
    if kind == "null":
        return ".null"
    if kind == "enum":
        return ".string(%s)" % swift_string(v)
    raise GraphQLError("неподдерживаемое значение %r" % (value,))


def swift_argument(value):
    kind, v = value
    if kind == "variable":
        return ".variable(%s)" % swift_string(v)
    if kind == "list":
        return ".list([" + ", ".join(swift_argument(x) for x in v) + "])"
    if kind == "object":
        return ".object([" + ", ".join("%s: %s" % (swift_string(k), swift_argument(x)) for k, x in v) + "])"
    return ".value(%s)" % swift_json(value)


def build():
    types, roots = parse_schema(SCHEMA.read_text(encoding="utf-8"), str(SCHEMA.relative_to(ROOT)))
    sources = sorted(OPERATIONS.glob("*.graphql"))
    if not sources:
        raise GraphQLError("в %s нет файлов .graphql" % OPERATIONS.relative_to(ROOT))
    parsed = []
    all_ops = []
    all_fragments = []
    for path in sources:
        ops, fragments = parse_operations(path.read_text(encoding="utf-8"), str(path.relative_to(ROOT)))
        parsed.append((path, ops, fragments))
        all_ops.extend(ops)
        all_fragments.extend(fragments)
    generator = Generator(types, roots, all_ops, all_fragments)
    files = {OUT / "SchemaTypes.swift": generator.schema_file()}
    for path, ops, fragments in parsed:
        files[OUT / (path.stem + ".graphql.swift")] = generator.operations_file(ops, fragments)
    return files


def main():
    try:
        files = build()
    except GraphQLError as e:
        sys.stderr.write("ошибка: %s\n" % e)
        sys.exit(1)
    existing = set(OUT.glob("*.swift")) if OUT.exists() else set()
    if "--check" in sys.argv[1:]:
        bad = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        bad += sorted(existing - set(files))
        if bad:
            sys.stderr.write("сгенерированный GraphQL-клиент устарел: запустите python3 scripts/gen-graphql-client.py\n")
            for p in bad:
                sys.stderr.write("  " + str(p.relative_to(ROOT)) + "\n")
            sys.exit(1)
        print("GraphQL-клиент совпадает с graphql/schema.graphql и операциями")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for p in existing - set(files):
        p.unlink()
    for p, text in files.items():
        p.write_text(text, encoding="utf-8")
    print("обновлено файлов: %d" % len(files))


if __name__ == "__main__":
    main()
