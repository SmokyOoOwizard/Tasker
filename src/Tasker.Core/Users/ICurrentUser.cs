namespace Tasker.Core.Users;

/// <summary>
/// Кто выполняет запрос. На сервере — пользователь из JWT (токен уже проверен, пользователь существует).
/// На десктопе — никто: там нет входа, и проверки прав не выполняются.
/// </summary>
public interface ICurrentUser
{
    /// <summary>null — запрос без входа (десктоп или открытые методы сервера: регистрация, вход).</summary>
    Guid? Id { get; }
}

/// <summary>Режим пользователей: сервер (вход и права) или десктоп (только имена).</summary>
/// <param name="RequireCredentials">
/// true — сервер: у пользователя обязательны почта и пароль, действия проверяются по правам.
/// false — десктоп: пользователь — только имя, проверок прав нет.
/// </param>
public record UserOptions(bool RequireCredentials);
